-- Chat/call tables contain private conversations; keep them out of the
-- anon role entirely.
revoke all on public.conversations, public.conversation_members, public.messages, public.voice_calls, public.voice_call_signals from anon;
grant select on public.conversations, public.conversation_members, public.messages, public.voice_calls, public.voice_call_signals to authenticated;
grant insert on public.messages, public.voice_calls, public.voice_call_signals to authenticated;
grant update on public.voice_calls to authenticated;

-- Make push notifications open the relevant area when the app is installed/opened.
-- This replaces the generic root URL used by the older V27 trigger while preserving
-- its safe no-op behavior when push dispatch isn't configured.
create or replace function public.push_notification_on_insert()
returns trigger
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_url text;
  v_key text;
  v_target text := '/';
begin
  begin
    v_url := current_setting('app.settings.supabase_url', true);
    v_key := current_setting('app.settings.service_role_key', true);
    if new.type in ('chat_message', 'voice_call') then v_target := '/messages'; end if;
    if v_url is null or v_key is null or v_url = '' or v_key = '' then return new; end if;
    perform net.http_post(
      url := v_url || '/functions/v1/send-push-notification',
      headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
      body := jsonb_build_object('user_id', new.user_id, 'title', case when new.type = 'voice_call' then 'Campus Crib call' else 'Campus Crib' end, 'body', new.message, 'url', v_target)
    );
  exception when others then null;
  end;
  return new;
end;
$$;
